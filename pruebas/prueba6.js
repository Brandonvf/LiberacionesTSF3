const { chromium, devices } = require('playwright'); const path = require('path'), fs = require('fs');
const URL = 'http://127.0.0.1:8765/';
const ADMIN = { uid: 'a1', email: 'brandonkluivertvillegasfranco@gmail.com', displayName: 'Brandon Villegas' };
const JEFE = { uid: 'j1', email: 'jefe@gmail.com', displayName: 'Jefe Prueba' };
const NUEVO = { uid: 'n1', email: 'nuevo@gmail.com', displayName: 'Topógrafo Nuevo' };
const errores = [];
const ok = (c, m) => { if (!c) { console.log('FALLA:', m); process.exitCode = 1; } else console.log('ok  -', m); };
(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ ...devices['iPhone 13'], acceptDownloads: true });
  await ctx.addInitScript(() => { new MutationObserver(() => { const f = document.querySelector('.dlg.on form:has(.dlg-p)'); if (f && !f.dataset.auto) { f.dataset.auto = 1; setTimeout(() => f.querySelector('[type=submit]').click(), 30); } }).observe(document, { childList: true, subtree: true, attributes: true, attributeFilter: ['class'] }); });
  await ctx.route(/gstatic\.com\/firebasejs\/.*\/(firebase-[a-z]+\.js)/, r => { const f = r.request().url().match(/(firebase-[a-z]+\.js)/)[1]; r.fulfill({ path: path.join(__dirname, 'fake', f), contentType: 'application/javascript' }); });
  await ctx.route(/fonts\./, r => r.abort());
  const p = await ctx.newPage(); p.on('pageerror', e => { errores.push(e.message); console.log('PAGEERROR', e.message); });
  const login = async u => { await p.evaluate(u => { window.__fakeLogin = u; }, u); await p.click('#gEntrar'); };
  const salir = async () => { await p.click('#btnSalir'); await p.waitForSelector('#gEntrar'); };
  await p.goto(URL); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForSelector('#gEntrar');
  await login(ADMIN); await p.waitForSelector('#nav button');
  await p.click('[data-v="ajustes"]'); await p.click('[data-tab="usuarios"]'); await p.waitForSelector('#uMail');
  await p.fill('#uMail', JEFE.email); await p.fill('#uNom', JEFE.displayName); await p.selectOption('#uRol', 'jefe'); await p.click('#uAdd'); await p.waitForTimeout(150);
  await salir();
  await login(NUEVO); await p.waitForSelector('text=Acceso solicitado'); await p.click('#gSalir'); await p.waitForSelector('#gEntrar');
  await login(JEFE); await p.waitForSelector('#nav button');
  const nav = await p.$$eval('#nav button', bs => bs.map(b => b.dataset.v));
  ok(nav.join() === 'panel,bandeja,todos,ajustes', 'jefe ve Panel, Bandeja (aspas), Registros y Ajustes: ' + nav.join());
  ok((await p.textContent('#nav [data-v="ajustes"]')).includes('1'), 'jefe ve el aviso de 1 solicitud');
  await p.click('[data-v="ajustes"]'); await p.waitForSelector('.tabs');
  const tabs = await p.$$eval('.tabs [data-tab]', t => t.map(x => x.dataset.tab));
  ok(tabs.join() === 'usuarios,lugares,capas,topografos,tipos,historico,archivos,exportar', 'mismas pestañas que el administrador');
  await p.click('[data-tab="usuarios"]'); await p.waitForSelector('[data-uid]');
  await p.selectOption('[data-uid] [data-k="topo"]', 'AB'); await p.click('[data-ap]'); await p.waitForTimeout(200);
  ok((await p.textContent('#usr')).includes('Topógrafo Nuevo'), 'jefe aprueba una solicitud');
  await p.click('[data-tab="lugares"]'); await p.waitForSelector('.est');
  await p.fill('#eNew', 'Presa Auxiliar Sur'); await p.click('#eAdd'); await p.waitForTimeout(200);
  ok((await p.$$eval('.est-h input', i => i.map(x => x.value))).includes('Presa Auxiliar Sur'), 'jefe agrega una estructura');
  await p.click('[data-tab="topografos"]'); await p.waitForSelector('#tpList');
  await p.fill('#tpId', 'HQ'); await p.fill('#tpNom', 'Hugo Quispe'); await p.click('#tpAdd'); await p.waitForTimeout(150);
  console.log('TOAST', await p.textContent('#toast'), '|', (await p.$$eval('#tpList .prow[data-i] .mono', m => m.map(x => x.textContent))).join(','));
  ok((await p.$$eval('#tpList [data-k="nom"]', i => i.map(x => x.value))).includes('Hugo Quispe'), 'jefe agrega un topógrafo');
  await p.click('[data-tab="capas"]'); await p.waitForSelector('#cSub');
  await p.fill('#cDe', '1'); await p.fill('#cA', '5'); await p.click('#cVarias'); await p.waitForTimeout(150);
  ok(await p.$$eval('.ct-row[data-i]', r => r.length) === 5, 'jefe agrega capas');
  await p.click('[data-tab="historico"]'); await p.waitForSelector('#hFile', { state: 'attached' });
  await p.setInputFiles('#hFile', path.join(__dirname, 'datos', 'historico-prueba.json')); await p.waitForSelector('#hImp:not([disabled])');
  await p.click('#hImp'); await p.waitForFunction(() => /Listo/.test(document.querySelector('#hEst').textContent), null, { timeout: 60000 });
  ok(true, 'jefe importa el histórico');
  await p.click('[data-tab="exportar"]'); await p.waitForSelector('#xReg'); await p.click('[data-r="todo"]');
  const [d] = await Promise.all([p.waitForEvent('download'), p.click('#xDia')]);
  ok(fs.readFileSync(await d.path(), 'utf8').split('\r\n').length > 100, 'jefe descarga el avance diario');
  await p.click('[data-v="bandeja"]'); await p.waitForTimeout(300);
  ok(!(await p.$('#view .tabs [data-bt="PT"]')) && await p.$('[data-asp="por"]'), 'la Bandeja del jefe solo tiene aspas (aceptar y entregar siguen siendo de gabinete)');
  console.log('Errores:', errores.length ? errores : 'ninguno');
  await b.close();
})().catch(e => { console.error(e); process.exit(1); });
